package zipx.agent

import zipx.core.EnvValue.secret
import zipx.core.{EnvValue, SbtCommand}
import zio.test.*

object CursorEnvSpec extends ZIOSpecDefault:

  private val pins = AgentPins(AgentPins.DefaultBase, AgentPins.DefaultDocker, AgentPins.DefaultSbtRunner)

  private def env(docker: Boolean, secrets: List[String]) =
    AgentEnv(
      docker = docker,
      rehydrate = SbtCommand.unsafeTask("Test/compile"),
      secretEnv = secrets,
      pins = pins,
    )

  private def files(docker: Boolean, secrets: List[String] = List("REGISTRY_TOKEN")) =
    CursorEnv.render(env(docker, secrets))

  def spec = suite("CursorEnv")(
    test("environment.json names the Dockerfile beside it and does not widen the build context") {
      val json = files(docker = true).fold(identity, _.environmentJson)
      assertTrue(
        !json.contains("context"),
        json.contains(""""dockerfile": "Dockerfile""""),
        json.contains("bash .github/zipx-agent/install.sh"),
        json.contains(""""start": "sudo service docker start""""),
      )
    },
    test("docker off omits the daemon and the start command") {
      val rendered = files(docker = false)
      assertTrue(
        rendered.exists(files =>
          !files.environmentJson.contains("start") &&
            files.dockerfile.exists(text =>
              !text.contains("fuse-overlayfs") &&
                !text.contains("docker-ce=") &&
                !text.contains("iptables-legacy")
            )
        )
      )
    },
    test("docker on pins 28 and the nested-docker setup, with no JDK and no hardcoded x86_64") {
      val docker = files(docker = true).fold(identity, _.dockerfile.getOrElse(""))
      assertTrue(
        docker.startsWith("# Generated by zipx."),
        docker.contains(s"FROM ubuntu:24.04@${AgentPins.DefaultBase}"),
        docker.contains(s"docker-ce=${AgentPins.DefaultDocker}"),
        docker.contains(s"docker-ce-cli=${AgentPins.DefaultDocker}"),
        docker.contains("fuse-overlayfs"),
        docker.contains("iptables-legacy"),
        docker.contains(s"sbt-${AgentPins.DefaultSbtRunner}.zip"),
        docker.contains("dpkg --print-architecture"),
        docker.contains("printf '%s\\n'"),
        !docker.contains("x86_64"),
        !docker.toLowerCase.contains("temurin"),
        !docker.contains("COPY "),
        !docker.contains("openjdk"),
      )
    },
    test("a shared sbt image is the agent image, and a daemon is FROM that image") {
      val image  = "sbtscala/scala-sbt:eclipse-temurin-21.0.12_8_2.x@sha256:" + ("ab" * 32)
      val plain  = CursorEnv.render(env(docker = false, List("GITHUB_TOKEN")).copy(toolchain = Some(image)))
      val daemon = CursorEnv.render(env(docker = true, List("GITHUB_TOKEN")).copy(toolchain = Some(image)))
      assertTrue(
        plain.exists { files =>
          files.environmentJson.contains(s""""image": "$image"""") &&
          files.dockerfile.isEmpty &&
          files.installSh.contains("Cursor Runtime Secret") &&
          files.installSh.contains("GITHUB_TOKEN") &&
          !files.installSh.contains("openjdk")
        },
        daemon.exists { files =>
          files.dockerfile.exists(_.contains(s"FROM $image")) &&
          files.environmentJson.contains(""""start": "service docker start"""")
        },
      )
    },
    test("install reads the JDK from zipx-ci.env, names secret env, and warms with a private sbt server") {
      val install = files(docker = true).fold(identity, _.installSh)
      assertTrue(
        install.startsWith("# Generated by zipx."),
        install.contains(". project/zipx-ci.env"),
        install.contains("REGISTRY_TOKEN"),
        install.contains("java.specification.version"),
        install.contains("already at /opt/jdk/current"),
        install.contains("dpkg --print-architecture"),
        install.contains("api.adoptium.net"),
        !install.contains("x86_64"),
        install.contains("export COURSIER_TTL=0s"),
        install.contains("sbt --server --batch 'Test/compile'"),
        install.contains("/usr/local/bin/java"),
        install.contains("""[ -z "${zipx_jdk_home:-}" ]"""),
      )
    },
    test("secret names are the env vars the build reads, sorted, and plain values are not secrets") {
      val names = ZipxAgentEnv.secretNames(
        Map(
          "COURSIER_TTL"   -> EnvValue.plain("0s"),
          "REGISTRY_TOKEN" -> secret"REGISTRY_TOKEN",
          "OTHER_TOKEN"    -> secret"SONATYPE_PASSWORD",
        )
      )
      assertTrue(names == Right(List("OTHER_TOKEN", "REGISTRY_TOKEN")))
    },
    test("a secret env name that is not a shell identifier is refused") {
      val names = ZipxAgentEnv.secretNames(Map("not-a-name" -> secret"NOT_A_NAME"))
      assertTrue(names.left.exists(_.contains("not-a-name")))
    },
  )
end CursorEnvSpec
